#!/usr/bin/env python3
"""Teach a Linux Device SDK checkout the reTerminal E1002's display commands.

Usage: patch_executor.py LINUX_SDK_DIR

Adds display.draw_url, display.show_animation and sensors.read to
src/musegadget/executor.py with the E1002 firmware's own descriptions, and
forwards them to the virtual reTerminal (`muse-briefing emulate`) at
$MUSE_RETERMINAL_SIM (default http://127.0.0.1:8766). Muse then drives the
virtual panel the way it would drive the real one. Standard library only.
"""

from __future__ import annotations

import pprint
import runpy
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPECS = HERE.parents[1] / "briefing/src/muse_briefing/emulator/specs.py"
MARK = "# --- virtual reTerminal E1002 (edu-ai-made-easy) ---"

SPEC_ANCHOR = "\n\n@dataclass(frozen=True)\nclass Account:"
RUN_ANCHOR = "        try:\n            if command == \"system.run\":"


def block(specs: dict) -> str:
    return f'''

{MARK}
# Generated by simulator/linux-gadget/patch_executor.py. Forwards the E1002's
# display commands to the virtual reTerminal (muse-briefing emulate).
RETERMINAL_SIM_URL = os.environ.get("MUSE_RETERMINAL_SIM", "http://127.0.0.1:8766").rstrip("/")
RETERMINAL_COMMANDS = {pprint.pformat(specs, width=100, sort_dicts=False)}
COMMAND_SPECS.update(RETERMINAL_COMMANDS)


def reterminal_forward(command: str, params: dict) -> dict:
    import urllib.request
    body = json.dumps({{"command": command, "params": params}}).encode()
    req = urllib.request.Request(RETERMINAL_SIM_URL + "/command", data=body,
                                 headers={{"Content-Type": "application/json"}})
    timeout_s = RETERMINAL_COMMANDS[command].get("timeout_ms", 30000) / 1000 + 5
    try:
        with urllib.request.urlopen(req, timeout=timeout_s) as r:
            return json.load(r)
    except OSError as exc:
        return error(f"virtual reTerminal not reachable at {{RETERMINAL_SIM_URL}}: {{exc}}")
# --- end virtual reTerminal ---
'''


def main() -> int:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    target = Path(sys.argv[1]) / "src/musegadget/executor.py"
    src = target.read_text()
    if MARK in src:
        print(f"{target} is already patched")
        return 0
    for anchor in (SPEC_ANCHOR, RUN_ANCHOR):
        if src.count(anchor) != 1:
            sys.exit(f"error: {target} doesn't match the pinned SDK (anchor {anchor.strip()[:40]!r}); "
                     "re-run firmware/fetch-sdk.sh")
    specs = runpy.run_path(str(SPECS))["COMMAND_SPECS"]
    src = src.replace(SPEC_ANCHOR, block(specs) + SPEC_ANCHOR, 1)
    src = src.replace(RUN_ANCHOR, RUN_ANCHOR.replace(
        "        try:\n",
        "        try:\n"
        "            if command in RETERMINAL_COMMANDS:\n"
        "                return reterminal_forward(command, params)\n", 1), 1)
    target.write_text(src)
    print(f"patched {target}: {', '.join(specs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
